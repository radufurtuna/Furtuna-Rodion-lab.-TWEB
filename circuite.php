                <p>Un rezistor este un component electric pasiv care limitează sau controlează curentul electric într-un circuit. Acesta joacă un rol esențial în majoritatea circuitelor electronice, având o valoare de rezistență măsurată în ohmi (Ω). Rezistența unui rezistor reprezintă opoziția pe care o oferă la trecerea curentului electric și depinde de materialul din care este fabricat și de dimensiunile sale.</p>
