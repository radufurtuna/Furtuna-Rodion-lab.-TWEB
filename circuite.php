                <h3>Condensator</h3>
                <img src="images/condensator.jpg"  />
                <p>CUn condensator este un component electric pasiv care stochează energie sub formă de câmp electric. </p>
                    <p>Acesta este format din două plăci conductoare separate de un material izolator, cunoscut sub numele de dielectric. </p>
                        <p> Condensatorii sunt utilizați într-o gamă largă de aplicații electronice și electrice, având rolul principal de a stoca și de a elibera energie rapid într-un circuit.</p>
            </div>
    
            <!-- Descriere componentă 3 -->
