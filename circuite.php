                <img src="images/bobina.jpg"  />
                <p>O bobină este un component pasiv utilizat în circuitele electronice și electrice, formată dintr-un fir conductor înfășurat în jurul unui miez (de obicei din material feromagnetic sau aer). </p>
                    <p>Bobina are capacitatea de a stoca energie sub formă de câmp magnetic atunci când curentul electric o traversează. De asemenea, bobinele sunt folosite pentru a controla curentul sau pentru a filtra semnalele electrice în diferite aplicații.</p>
