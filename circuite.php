                <h3>Dioda</h3>
                <img src="images/dioda.jpg"  />
                <p>O diodă este un component electronic semiconductoare care permite curentului electric să circule într-o singură direcție, blocându-l în cealaltă direcție. </p>
                    <p> Aceasta funcționează pe baza proprietăților semiconductoare ale materialelor din care este realizată, cum ar fi siliciul sau germaniul. Diodele sunt folosite într-o gamă largă de aplicații, inclusiv în redresoare, protecția circuitelor, comutarea semnalelor și chiar în iluminarea cu LED-uri.</p>
            </div>

